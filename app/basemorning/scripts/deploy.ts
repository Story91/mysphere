const hre = require("hardhat");
const { ethers } = require("hardhat");
const { writeFileSync, readFileSync } = require("fs");
const { join } = require("path");
require("dotenv").config();

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log("Deploying contracts with account:", deployer.address);
  console.log("Network:", hre.network.name);

  // Deploy BaseElementNFT
  const BaseElementNFT = await ethers.getContractFactory("BaseElementNFT");
  const baseElementNFT = await BaseElementNFT.deploy();
  await baseElementNFT.waitForDeployment();
  const baseElementNFTAddress = await baseElementNFT.getAddress();
  console.log("BaseElementNFT deployed to:", baseElementNFTAddress);

  // Chainlink VRF configuration
  const vrfCoordinator = process.env.CHAINLINK_VRF_COORDINATOR;
  const keyHash = process.env.CHAINLINK_KEY_HASH;
  const subscriptionId = process.env.CHAINLINK_SUBSCRIPTION_ID;

  if (!vrfCoordinator || !keyHash || !subscriptionId) {
    throw new Error("Missing Chainlink VRF configuration in .env file (CHAINLINK_VRF_COORDINATOR, CHAINLINK_KEY_HASH, CHAINLINK_SUBSCRIPTION_ID)");
  }

  // Deploy BaseMorningGame
  const BaseMorningGame = await ethers.getContractFactory("BaseMorningGame");
  const baseMorningGame = await BaseMorningGame.deploy(
    baseElementNFTAddress,
    vrfCoordinator,
    subscriptionId,
    keyHash
  );
  await baseMorningGame.waitForDeployment();
  const baseMorningGameAddress = await baseMorningGame.getAddress();
  console.log("BaseMorningGame deployed to:", baseMorningGameAddress);

  // Grant MINTER_ROLE to game contract
  const MINTER_ROLE = await baseElementNFT.MINTER_ROLE();
  await baseElementNFT.grantRole(MINTER_ROLE, baseMorningGameAddress);
  console.log("Granted MINTER_ROLE to game contract");

  // Update contract addresses and ABIs in configuration
  const configPath = join(__dirname, "../config/contract.ts");
  
  const gameArtifactPath = join(__dirname, "../../artifacts/contracts/BaseMorningGame.sol/BaseMorningGame.json");
  const nftArtifactPath = join(__dirname, "../../artifacts/contracts/BaseElementNFT.sol/BaseElementNFT.json");
  
  const gameArtifact = JSON.parse(readFileSync(gameArtifactPath, "utf8"));
  const nftArtifact = JSON.parse(readFileSync(nftArtifactPath, "utf8"));

  const configContent = `
// This file is auto-generated by the deploy script.
// Do not edit manually.

export const CONTRACT_ADDRESS = "${baseMorningGameAddress}" as const;
export const NFT_CONTRACT_ADDRESS = "${baseElementNFTAddress}" as const;

export const CONTRACT_ABI = ${JSON.stringify(gameArtifact.abi, null, 2)} as const;
export const NFT_CONTRACT_ABI = ${JSON.stringify(nftArtifact.abi, null, 2)} as const;
`;

  try {
    writeFileSync(configPath, configContent);
    console.log("Contract configuration updated successfully!");
  } catch (error) {
    console.error("Failed to update contract configuration:", error);
  }

  // Verify contracts on Base Sepolia Explorer
  if (process.env.BASESCAN_API_KEY) {
    console.log("Waiting for 5 blocks confirmations before verification...");
    await new Promise(resolve => setTimeout(resolve, 60000)); // Wait 1 minute

    console.log("Verifying contracts on Base Sepolia Explorer...");
    
    try {
      await hre.run("verify:verify", {
        address: baseElementNFTAddress,
        constructorArguments: []
      });
      console.log("BaseElementNFT verified");
    } catch (error) {
      console.log("BaseElementNFT verification failed:", error.message);
    }

    try {
      await hre.run("verify:verify", {
        address: baseMorningGameAddress,
        constructorArguments: [
          baseElementNFTAddress,
          vrfCoordinator,
          subscriptionId,
          keyHash
        ]
      });
      console.log("BaseMorningGame verified");
    } catch (error) {
      console.log("BaseMorningGame verification failed:", error.message);
    }
  } else {
    console.log("Skipping contract verification - BASESCAN_API_KEY not found in .env");
  }

  console.log("\nDeployment Summary:");
  console.log("-------------------");
  console.log("BaseElementNFT:", baseElementNFTAddress);
  console.log("BaseMorningGame:", baseMorningGameAddress);
  console.log("Network:", hre.network.name);
  console.log("Deployer:", deployer.address);
  console.log("-------------------\n");
}

main()
  .then(() => process.exit(0))
  .catch(error => {
    console.error(error);
    process.exit(1);
  }); 