// Adresy kontraktów - DO UZUPEŁNIENIA PO DEPLOYU
// Mainnet: wdróż przez Hardhat na neonmainnet
// Devnet: wdróż przez Hardhat na neondevnet
export let NEON_MAINNET_CONTRACT_ADDRESS = '0x0000000000000000000000000000000000000000'; // TODO: Deploy i uzupełnij
export let NEON_DEVNET_CONTRACT_ADDRESS = '0x0000000000000000000000000000000000000000'; // TODO: Deploy i uzupełnij

// Funkcja do ustawiania adresu kontraktu po deployu
export const setNeonContractAddress = (address: string, isDevnet: boolean = false) => {
  if (isDevnet) {
    NEON_DEVNET_CONTRACT_ADDRESS = address;
  } else {
    NEON_MAINNET_CONTRACT_ADDRESS = address;
  }
};

// Funkcja do pobierania adresu kontraktu w zależności od sieci
export const getNeonContractAddress = (chainId: number) => {
  if (chainId === NEON_MAINNET_CHAIN_ID) {
    return NEON_MAINNET_CONTRACT_ADDRESS;
  }
  if (chainId === NEON_DEVNET_CHAIN_ID) {
    return NEON_DEVNET_CONTRACT_ADDRESS;
  }
  return undefined;
};

// Export aktualnego adresu w zależności od konfiguracji
export const NEON_CONTRACT_ADDRESS = process.env.NEXT_PUBLIC_USE_NEON_DEVNET === 'true'
  ? NEON_DEVNET_CONTRACT_ADDRESS
  : NEON_MAINNET_CONTRACT_ADDRESS;

